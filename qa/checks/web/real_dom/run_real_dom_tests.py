#!/usr/bin/env python3
"""Run Companion UI tests against a real browser DOM.

The Node-based web tests use a hand-written fake DOM, so they cannot observe
how a browser actually parses, sanitizes or renders markup. This runner serves
the repository, replaces only the generated WASM package with a scriptable fake,
and executes `*.dom.mjs` suites inside headless Chromium.
"""

from __future__ import annotations

import argparse
import contextlib
import http.server
import json
from pathlib import Path
import re
import sys
import tempfile
import threading
import time
import urllib.parse

ROOT = Path(__file__).resolve().parents[4]
SUITE_ROOT = Path(__file__).resolve().parent
API = ROOT / "apps/kaskold-companion-web/web/js/wasm/api.js"
PACKAGE_PATH = "/apps/kaskold-companion-web/web/pkg/companion_web.js"
RESULT_PATH = "/__qa_real_dom_result__"
PAGE_PATH = "/__qa_real_dom__"
MAX_RESULT_BYTES = 1024 * 1024

sys.path.insert(0, str(ROOT / "qa/checks/integration"))
from real_node_browser import (  # noqa: E402
    RealNodeBrowserError,
    browser_executable,
    browser_log_tail,
    cleanup_chromium_profile,
    free_port,
    launch_chromium,
    open_chromium_target,
    stop_chromium,
)


def wasm_export_names(api_source: str) -> list[str]:
    """Names the Companion WASM facade forwards to the generated package."""
    return sorted(set(re.findall(r"invoke\('([A-Za-z0-9_]+)'", api_source)))


def fake_package(names: list[str]) -> str:
    """A WASM package whose exports delegate to per-test fakes."""
    lines = [
        "// Generated by qa/checks/web/real_dom/run_real_dom_tests.py.",
        "const fakes = () => globalThis.__kaskoldWasmFakes || {};",
        "function call(name, args) {",
        "  const fake = fakes()[name];",
        "  if (typeof fake !== 'function') throw new Error(`unfaked WASM export: ${name}`);",
        "  return fake(...args);",
        "}",
        "export default async function init() {}",
    ]
    lines.extend(f"export function {name}(...args) {{ return call('{name}', args); }}" for name in names)
    return "\n".join(lines) + "\n"


def suite_paths(selected: list[str]) -> list[str]:
    suites = sorted(SUITE_ROOT.glob("*.dom.mjs"))
    if selected:
        suites = [path for path in suites if path.name in selected]
    return ["/" + path.relative_to(ROOT).as_posix() for path in suites]


def page(suites: list[str]) -> bytes:
    imports = json.dumps(suites)
    return f"""<!doctype html><html><head><meta charset="utf-8"></head><body><script type="module">
import {{ runRegisteredTests }} from '/qa/checks/web/real_dom/harness.mjs';
const report = async (status, detail) => {{
  await fetch('{RESULT_PATH}', {{ method: 'POST', headers: {{ 'Content-Type': 'application/json' }},
    body: JSON.stringify({{ status, detail }}) }});
}};
try {{
  for (const suite of {imports}) await import(suite);
  const results = await runRegisteredTests();
  await report(results.every(result => result.ok) ? 'pass' : 'fail', {{ results }});
}} catch (error) {{
  await report('fail', {{ results: [{{ name: 'suite load', ok: false, error: String(error && error.stack || error) }}] }});
}}
</script></body></html>""".encode()


class Handler(http.server.SimpleHTTPRequestHandler):
    result_event = threading.Event()
    result: dict[str, object] | None = None
    suites: list[str] = []
    package = ""

    def log_message(self, _format: str, *_args: object) -> None:
        pass

    def guess_type(self, path: str) -> str:
        if Path(urllib.parse.urlsplit(path).path).suffix in {".js", ".mjs"}:
            return "text/javascript"
        return super().guess_type(path)

    def _send(self, body: bytes, content_type: str) -> None:
        self.send_response(200)
        self.send_header("Content-Type", content_type)
        self.send_header("Cache-Control", "no-store")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self) -> None:  # noqa: N802 - stdlib handler API
        path = urllib.parse.urlsplit(self.path).path
        if path == PAGE_PATH:
            self._send(page(type(self).suites), "text/html; charset=utf-8")
        elif path == PACKAGE_PATH:
            self._send(type(self).package.encode(), "text/javascript")
        elif path == "/favicon.ico":
            self.send_response(204)
            self.end_headers()
        else:
            super().do_GET()

    def do_POST(self) -> None:  # noqa: N802 - stdlib handler API
        length = int(self.headers.get("Content-Length", "0") or 0)
        if self.path != RESULT_PATH or not 0 < length <= MAX_RESULT_BYTES:
            self.send_error(400)
            return
        type(self).result = json.loads(self.rfile.read(length))
        self.send_response(204)
        self.end_headers()
        type(self).result_event.set()


@contextlib.contextmanager
def serve() -> int:
    port = free_port()
    server = http.server.ThreadingHTTPServer(
        ("127.0.0.1", port),
        lambda *args, **kwargs: Handler(*args, directory=str(ROOT), **kwargs),
    )
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        yield port
    finally:
        server.shutdown()
        thread.join(timeout=5)
        server.server_close()


def run(selected: list[str], timeout: int) -> dict[str, object]:
    Handler.suites = suite_paths(selected)
    if not Handler.suites:
        raise RealNodeBrowserError("no real-DOM suites found")
    Handler.package = fake_package(wasm_export_names(API.read_text(encoding="utf-8")))
    Handler.result = None
    Handler.result_event.clear()
    profile = Path(tempfile.mkdtemp(prefix="kaskold-real-dom-"))
    try:
        with serve() as port, tempfile.TemporaryFile(mode="w+", encoding="utf-8") as log:
            debug_port = free_port()
            process = launch_chromium(browser_executable(), debug_port, profile, log)
            try:
                open_chromium_target(debug_port, f"http://127.0.0.1:{port}{PAGE_PATH}")
                deadline = time.monotonic() + timeout
                while not Handler.result_event.wait(timeout=0.25):
                    if time.monotonic() > deadline or process.poll() is not None:
                        raise RealNodeBrowserError(
                            "real-DOM suites returned no result\n" + browser_log_tail(log)
                        )
            finally:
                stop_chromium(process)
    finally:
        cleanup_chromium_profile(profile)
    if Handler.result is None:
        raise RealNodeBrowserError("real-DOM suites returned no result")
    return Handler.result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("suites", nargs="*", help="limit to these *.dom.mjs file names")
    parser.add_argument("--timeout", type=int, default=120)
    args = parser.parse_args()
    try:
        result = run(args.suites, args.timeout)
    except (OSError, RealNodeBrowserError) as error:
        print(f"ERROR: {error}")
        return 1
    results = result.get("detail", {}).get("results", [])
    failed = [entry for entry in results if not entry.get("ok")]
    for entry in failed:
        print(f"FAIL: {entry.get('name')}\n{entry.get('error')}")
    if failed or result.get("status") != "pass" or not results:
        print(f"ERROR: {len(failed)} of {len(results)} real-DOM tests failed")
        return 1
    print(f"PASS: {len(results)} Companion UI tests in a real browser DOM")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
