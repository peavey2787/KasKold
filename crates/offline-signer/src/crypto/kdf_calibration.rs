//! Fixed, public Argon2id calibration inputs and their reference outputs.
//!
//! The firmware's Argon2/PSRAM benchmark runs these on the device and compares
//! each result with `expected`; the host unit test recomputes every `expected`
//! through the same Kaspa Portal KDF, so a KDF change cannot leave the device
//! comparing against stale values. Never put wallet credentials or seed data here.

use super::password_kdf::{
    PasswordKdfParams, PasswordKdfPurpose, ARGON2_VERSION_13, PROFILE_VERSION_1, SALT_SIZE,
};

pub const PURPOSE: PasswordKdfPurpose = PasswordKdfPurpose::PortableBackup;
pub const PASSWORD: &[u8] = b"KasKold Argon2 benchmark v1";
pub const SALT: [u8; SALT_SIZE] = [
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
];
pub const T_COST: u32 = 3;
pub const P_COST: u32 = 1;

/// One workspace size the device must derive correctly, with its known output.
pub struct Candidate {
    pub memory_kib: u32,
    pub expected: [u8; 32],
}

impl Candidate {
    #[must_use]
    pub const fn parameters(&self) -> PasswordKdfParams {
        PasswordKdfParams {
            profile_version: PROFILE_VERSION_1,
            argon_version: ARGON2_VERSION_13,
            m_cost_kib: self.memory_kib,
            t_cost: T_COST,
            p_cost: P_COST,
        }
    }
}

